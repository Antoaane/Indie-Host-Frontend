# Déjà respecté ci‑dessus (PARKING_FOR_TWO_CARS, puis PRIVATE_PARKING, puis FREE_PARKING_ON_PREMISES).


def _normalize_for_match(text: str) -> str:
    if not text:
        return ""
    s = unicodedata.normalize("NFD", text)
    s = "".join(c for c in s if unicodedata.category(c) != "Mn")
    s = s.lower().strip()
    s = re.sub(r"[^a-z0-9\s]", " ", s)
    s = re.sub(r"\s+", " ", s)
    return s


def _build_match_candidates(title: str, subtitle: str) -> set[str]:
    candidates: set[str] = set()
    normalized_title = _normalize_for_match(title)
    normalized_subtitle = _normalize_for_match(subtitle)

    for value in (normalized_title, normalized_subtitle):
        if value:
            candidates.add(value)
            candidates.add(value.replace(" ", ""))

    if normalized_title and normalized_subtitle:
        combined = f"{normalized_title} {normalized_subtitle}".strip()
        candidates.add(combined)
        candidates.add(combined.replace(" ", ""))

    return candidates


def map_airbnb_amenity_to_indiehost(
    title: str,
    subtitle: str = "",
    category: str = "",
) -> dict[str, Any] | None:
    """
    Retourne l'amenity IndieHost correspondant au libellé Airbnb, ou None.

    title, subtitle, category : chaînes brutes renvoyées par le scraper Airbnb.
    """
    candidates = _build_match_candidates(title, subtitle)
    if not candidates:
        return None

    for entry in INDIEHOST_AMENITIES:
        patterns = entry.get("patterns") or []
        for pat in patterns:
            norm_pat = _normalize_for_match(pat)
            if not norm_pat:
                continue
            compact_pat = norm_pat.replace(" ", "")
            if norm_pat in candidates or compact_pat in candidates:
                out = {
                    "id": entry["id"],
                    "name": entry["name"],
                    "description": subtitle.strip() if subtitle else "",
                    "category": entry["category"],
                    "relevance": entry.get("relevance", 50),
                    "perkEligible": entry.get("perkEligible", False),
                    "perkScore": entry.get("perkScore"),
                    "perkPriority": entry.get("perkPriority"),
                }
                return {k: v for k, v in out.items() if v is not None and v != ""}
    return None


def translate_amenities_to_indiehost(
    raw_amenities: list[dict[str, Any]],
    highlight_titles: list[str] | None = None,
) -> list[dict[str, Any]]:
    """
    Traduit les amenities brutes Airbnb (groupes avec values) en liste
    d'amenities typées IndieHost.

    raw_amenities : liste de { "title": "Catégorie", "values": [ {"title", "subtitle?", "available?"} ] }
    highlight_titles : titres des "points forts" Airbnb pour marquer pinned / relevance élevée.
    """
    highlight_set = set()
    if highlight_titles:
        highlight_set = {_normalize_for_match(h) for h in highlight_titles if h}

    seen_ids: set[str] = set()
    seen_keys: set[str] = set()
    out: list[dict[str, Any]] = []

    for group in raw_amenities or []:
        group_title = (group.get("title") or "").strip()
        values = group.get("values") or group.get("items") or []
        for item in values:
            if not isinstance(item, dict):
                continue
            if item.get("available") is False:
                continue
            title = (item.get("title") or item.get("name") or item.get("label") or "").strip()
            if not title:
                continue
            subtitle = (item.get("subtitle") or item.get("description") or "").strip()
            mapped = map_airbnb_amenity_to_indiehost(title, subtitle, group_title)
            if mapped:
                aid = mapped.get("id") or ""
                key = f"{group_title}::{title}"
                if aid in seen_ids or key in seen_keys:
                    continue
                seen_ids.add(aid)
                seen_keys.add(key)
                if highlight_set and _normalize_for_match(title) in highlight_set:
                    mapped["relevance"] = max(mapped.get("relevance", 0), 95)
                    mapped["pinned"] = True
                out.append(mapped)
    return out
